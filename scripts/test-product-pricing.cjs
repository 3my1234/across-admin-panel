const assert = require('node:assert/strict');
require('../delivery-areas.js');
const {payload, fromSaved} = globalThis.ProviderDeliveryAreas;
const primary = {country:'NG',state:'',city:'',fee:'5',currency:'NGN',custom:false,price:'',confirmed:false};
assert.equal(payload([primary],100,'NGN')[0].item_price,100);
assert.equal(payload([primary],200,'NGN')[0].item_price,200);
assert.equal(payload([primary],200,'NGN')[0].delivery_fee,5);
assert.equal(payload([primary],200,'NGN')[0].uses_primary_price,true);
const stale = fromSaved([{country_code:'NG',delivered_price:25,delivery_fee:5,currency_code:'NGN',uses_primary_price:false}],100,'NGN');
assert.throws(()=>payload(stale,100,'NGN'),/confirm the different price/);
stale[0].confirmed=true;
assert.equal(payload(stale,100,'NGN')[0].item_price,20);
assert.equal(payload(stale,100,'NGN')[0].independent_price_confirmed,true);
stale[0].custom=false;
assert.equal(payload(stale,100,'NGN')[0].item_price,100);
const foreign={...primary,country:'US',currency:'USD',custom:true,price:'30',confirmed:true};
assert.equal(payload([primary,foreign],100,'NGN')[1].item_price,30);
assert.throws(()=>payload([{...foreign,custom:false}],100,'NGN'),/Check the product price/);
assert.throws(()=>payload([{...primary,city:'Abuja'}],100,'NGN'),/Enter the state/);
assert.throws(()=>payload([{...primary,fee:''}],100,'NGN'),/delivery charge/);
assert.throws(()=>payload([{...primary,fee:'-1'}],100,'NGN'),/delivery charge/);
assert.throws(()=>payload([],100,'NGN'),/between 1 and 20/);
assert.throws(()=>payload(Array(21).fill(primary),100,'NGN'),/between 1 and 20/);
assert.equal(fromSaved([{country_code:'NG',delivered_price:105,delivery_fee:5,currency_code:'NGN'}],100,'NGN')[0].custom,false);
console.log('Delivery pricing passed: follow main price, preserve delivery fees, require explicit separate prices, validate areas.');
